// Protocol source of truth: official EasyTier v2.6.4, never a moving branch.
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import protobuf from 'protobufjs';

const root = new URL('../', import.meta.url);
const version = 'v2.6.4';
const commit = '8428a89d2dabc94c97d370ec607c6ca142473626';
const base = `https://raw.githubusercontent.com/EasyTier/EasyTier/${commit}/`;
const sources = ['common.proto', 'error.proto', 'peer_rpc.proto'];
const generatorPath = 'easytier-rpc-build/src/lib.rs';
const normalize = text => text.replace(/\r\n/g, '\n');
const digest = text => createHash('sha256').update(normalize(text)).digest('hex');
const canonical = text => normalize(text).replace(/[\t ]+$/gm, '');
const get = async path => {
  const response = await fetch(base + path);
  if (!response.ok) throw new Error(`Upstream ${path}: HTTP ${response.status}`);
  return response.text();
};
const check = process.argv.includes('--check');
if (process.argv.length > 2 && !check) throw new Error('Usage: node scripts/sync-upstream.mjs [--check]');
const lockPath = new URL('protos/upstream.json', root);
let lock;
if (check) {
  lock = JSON.parse(await readFile(lockPath, 'utf8'));
  if (lock.version !== version || lock.commit !== commit) throw new Error('Unexpected upstream version');
  for (const name of sources) {
    if (digest(await readFile(new URL(`protos/${name}`, root), 'utf8')) !== lock.files[name].normalizedSha256) {
      throw new Error(`${name} differs from locked upstream source`);
    }
  }
} else {
  // Fetch and validate everything before changing any local protocol file.
  const content = await Promise.all(sources.map(name => get(`easytier/src/proto/${name}`)));
  const generator = await get(generatorPath);
  if (!/index\s*=\s*idx\s*\+\s*1/.test(generator)) throw new Error('Upstream RPC numbering rule changed');
  lock = { version, commit, files: {}, rpcGenerator: { path: generatorPath, sha256: digest(generator), methodIndexBase: 1 } };
  for (let i = 0; i < sources.length; i++) {
    const name = sources[i];
    lock.files[name] = { path: `easytier/src/proto/${name}`, sha256: digest(content[i]), normalizedSha256: digest(canonical(content[i])) };
    await writeFile(new URL(`protos/${name}`, root), canonical(content[i]));
  }
  await writeFile(lockPath, JSON.stringify(lock, null, 2) + '\n');
}

const schema = await new protobuf.Root().load(fileURLToPath(new URL('protos/peer_rpc.proto', root)));
const services = schema.lookup('peer_rpc').nestedArray.filter(value => value instanceof protobuf.Service);
const lines = [
  `// Generated by scripts/sync-upstream.mjs from EasyTier ${version} (${commit}).`,
  '// The upstream Rust RPC generator numbers methods from 1 in declaration order.',
  'export const RPC_METHODS = Object.freeze({',
];
for (const service of services) {
  lines.push(`  ${service.name}: Object.freeze({`);
  for (const [index, method] of service.methodsArray.entries()) lines.push(`    ${method.name}: ${index + 1},`);
  lines.push('  }),');
}
lines.push('});', '');
const methods = lines.join('\n');
const methodsPath = new URL('src/worker/core/rpc_methods.js', root);
if (check) {
  if (normalize(await readFile(methodsPath, 'utf8')) !== methods) throw new Error('RPC method constants are stale');
} else await writeFile(methodsPath, methods);
console.log(`PASS: ${version} protocol sources and RPC method definitions ${check ? 'verified' : 'synchronized'} (${commit})`);
